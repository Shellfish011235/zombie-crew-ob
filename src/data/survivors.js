export function getSurvivor(id) {
  return survivors.find((s) => s.id === id) ?? null;
}

export function getSurvivorAbility(id) {
  const s = getSurvivor(id);
  if (!s) return null;
  return {
    name: s.abilityName,
    description: s.abilityDescription,
    outrunBonus: s.outrunBonus,
    plateBonus: s.plateBonus,
    globalBonus: s.globalBonus,
    passives: s.passives,
  };
}

/** Legacy shape for older imports */
export function toLegacyPlayer(s) {
  return { ...s, role: s.title, image: s.img, description: s.abilityDescription };
}

export const players = survivors.map(toLegacyPlayer);
